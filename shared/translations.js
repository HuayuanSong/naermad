export function translate(source, language = "da", values = {}) {
  const message =
    language === "en" && Object.hasOwn(english, source)
      ? english[source]
      : source;
  return message.replace(/\{(\w+)\}/g, (match, key) =>
    values[key] === undefined ? match : String(values[key]),
  );
}

export function translateError(message, language = "da") {
  if (language !== "en") return message;
  if (Object.hasOwn(english, message)) return english[message];
  let match = message.match(/^Varen “(.*)” har et uklart navn\./s);
  if (match)
    return `The product “${match[1]}” has an unclear name. Choose a more descriptive product so the model does not have to guess.`;
  match = message.match(/^(?:Angiv|Vælg) 1–(\d+) varer,/);
  if (match) return `Choose 1–${match[1]} products to cook with.`;
  match = message.match(
    /^Salling beder os vente\. Prøv igen om (\d+) sekunder\.$/,
  );
  if (match)
    return `Salling asks us to wait. Try again in ${match[1]} seconds.`;
  match = message.match(
    /^Salling beder os vente\. Prøv igen om cirka (\d+) minutter\.$/,
  );
  if (match)
    return `Salling asks us to wait. Try again in about ${match[1]} minutes.`;
  return message;
}
